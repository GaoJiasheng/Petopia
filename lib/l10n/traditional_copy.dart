  static String translate(String source) {
    if (source.isEmpty || EnglishCopy.translate(source) == source) {
      return source;
    }
    return translateKnown(source);
  }

  static String translateKnown(String source) {
    final exact = _exact[source];
    if (exact != null) return exact;

    var converted = source;
    for (final (simplified, traditional) in _phrases) {
      converted = converted.replaceAll(simplified, traditional);
    }

    final buffer = StringBuffer();
    for (final rune in converted.runes) {
      final index = _simplifiedRunes.indexOf(rune);
      buffer.writeCharCode(index < 0 ? rune : _traditionalRunes[index]);
    }
    return buffer.toString();
  }

  static final List<int> _simplifiedRunes = _simplified.runes.toList(
    growable: false,
  );
